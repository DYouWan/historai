export function themeBuiltInCharacters(seriesTitle: string): string[] {
  const list = SERIES_BUILT_IN_PICKS[seriesTitle.trim()];
  return list?.map((p) => p.character) ?? [];
}

export function themeBuiltInSlices(
  seriesTitle: string,
  character: string,
): SliceSuggestion[] {
  const list = SERIES_BUILT_IN_PICKS[seriesTitle.trim()];
  const row = list?.find((p) => p.character === character.trim());
  return row?.slices ? row.slices.map((s) => ({ ...s })) : [];
}
